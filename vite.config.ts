import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { resolve } from 'path';
import fs from 'fs';

// Production build: backend only, no localhost, API origin from VITE_API_URL (must be https).
const isProdBuild = process.env.VITE_BUILD_TARGET === 'production';
const DEFAULT_PROD_API = 'https://bshelper.duckdns.org';
const apiUrl = (process.env.VITE_API_URL || (isProdBuild ? DEFAULT_PROD_API : 'http://localhost:3000')).replace(/\/+$/, '');
if (isProdBuild && !/^https:\/\/[^/]+$/.test(apiUrl)) {
  throw new Error('Production build needs VITE_API_URL=https://your-api-host (no path, https only).');
}
process.env.VITE_API_URL = apiUrl; // make the default visible to import.meta.env
// Each build target has its own output folder so the online and dev extensions can be loaded side by side.
const outName = process.env.VITE_OUT_DIR || (isProdBuild ? 'dist-online' : 'dist-dev');
const LOCAL_PATTERNS = ['http://localhost/*', 'http://127.0.0.1/*'];

export default defineConfig({
  plugins: [
    react(),
    {
      name: 'copy-manifest-and-assets',
      closeBundle() {
        const distDir = resolve(__dirname, outName);
        const assetsDir = resolve(distDir, 'assets');
        if (!fs.existsSync(distDir)) fs.mkdirSync(distDir, { recursive: true });
        if (!fs.existsSync(assetsDir)) fs.mkdirSync(assetsDir, { recursive: true });

        // Copy manifest.json to dist/manifest.json
        const manifestSrc = resolve(__dirname, 'src/manifest.json');
        if (fs.existsSync(manifestSrc)) {
          const manifest = JSON.parse(fs.readFileSync(manifestSrc, 'utf-8'));
          // match patterns have no port: scheme + hostname only
          const u = new URL(apiUrl);
          const apiOrigin = `${u.protocol}//${u.hostname}/*`;
          const hosts = new Set<string>(manifest.host_permissions ?? []);
          hosts.add(apiOrigin);
          if (isProdBuild) {
            LOCAL_PATTERNS.forEach((p) => hosts.delete(p));
            for (const cs of manifest.content_scripts ?? []) {
              cs.matches = (cs.matches ?? []).filter((m: string) => !LOCAL_PATTERNS.includes(m));
            }
            manifest.web_accessible_resources = (manifest.web_accessible_resources ?? []).map((w: any) => ({
              ...w,
              resources: (w.resources ?? []).filter((r: string) => !r.startsWith('test-page')),
            }));
          }
          if (!isProdBuild) manifest.name = `${manifest.name} (dev)`;
          manifest.host_permissions = [...hosts];
          fs.writeFileSync(resolve(distDir, 'manifest.json'), JSON.stringify(manifest, null, 2));
        }

        // Copy extension icons (generated by scripts/make-icons.py)
        fs.cpSync(resolve(__dirname, 'src/icons'), resolve(distDir, 'icons'), { recursive: true });

        // Copy test-page directory to dist/test-page if it exists
        const testPageSrc = resolve(__dirname, 'test-page');
        if (!isProdBuild && fs.existsSync(testPageSrc)) {
          fs.cpSync(testPageSrc, resolve(distDir, 'test-page'), { recursive: true });
        }

        // Write content script loader for MV3 dynamic import safety + pre-paint sidebar placeholder
        const loaderPath = resolve(assetsDir, 'content-loader.js');
        const loaderCode = `(() => {
  try {
    const isOpen = localStorage.getItem('brightspace-ai-drawer-open') === '1';
    const isExpanded = localStorage.getItem('brightspace-ai-drawer-expanded') === '1';
    if (isOpen) {
      const style = document.createElement('style');
      style.id = 'brightspace-ai-prepaint-style';
      style.textContent = isExpanded
        ? 'body::after { content: ""; position: fixed; top: 0; right: 0; width: 100vw; height: 100vh; background: #ffffff; z-index: 2147483645; pointer-events: none; }'
        : 'body { margin-right: min(100vw, 460px) !important; } body::after { content: ""; position: fixed; top: 0; right: 0; width: min(100vw, 460px); height: 100vh; background: #f8fafc; border-left: 1px solid #e2e8f0; z-index: 2147483645; pointer-events: none; }';
      (document.head || document.documentElement).appendChild(style);
    }
  } catch (e) {}
  import(chrome.runtime.getURL('assets/content.js')).catch((e) => {
    console.error('[BS Helper] Failed to load content script:', e);
  });
})();
`;
        fs.writeFileSync(loaderPath, loaderCode, 'utf-8');
      },
    },
  ],
  resolve: {
    alias: {
      '@': resolve(__dirname, 'src'),
    },
  },
  build: {
    outDir: outName,
    emptyOutDir: true,
    sourcemap: process.env.NODE_ENV !== 'production',
    rollupOptions: {
      input: {
        content: resolve(__dirname, 'src/content/index.tsx'),
        background: resolve(__dirname, 'src/background/serviceWorker.ts'),
      },
      output: {
        entryFileNames: 'assets/[name].js',
        chunkFileNames: 'assets/chunks/[name]-[hash].js',
        assetFileNames: 'assets/[name].[ext]',
      },
    },
  },
  test: {
    globals: true,
    environment: 'jsdom',
    // Existing UI/gateway tests exercise the direct-Gemini development mode; backend mode has its own tests.
    env: { VITE_DEV_DIRECT_GEMINI: '1' },
    setupFiles: ['./tests/setup.ts'],
    testTimeout: 15000,
    include: ['tests/**/*.{test,spec}.?(c|m)[jt]s?(x)'],
    coverage: {
      reporter: ['text', 'json', 'html'],
    },
  },
});
